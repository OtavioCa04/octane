-- Carros da garagem. O slug forma o link público: /usuario/golf-gti

CREATE TABLE veiculos (
  id INTEGER PRIMARY KEY AUTO_INCREMENT,
  usuario_id INTEGER NOT NULL,
  slug VARCHAR(140) NOT NULL,
  marca VARCHAR(80) NOT NULL,
  modelo VARCHAR(120) NOT NULL,
  versao VARCHAR(120) NULL,
  ano_fabricacao INTEGER NOT NULL,
  ano_modelo INTEGER NOT NULL,
  motor VARCHAR(60) NULL,
  cambio VARCHAR(60) NULL,
  combustivel VARCHAR(30) NULL,
  cor VARCHAR(60) NULL,
  cor_hex CHAR(7) NULL,
  carroceria VARCHAR(20) NULL,
  quilometragem INTEGER NOT NULL DEFAULT 0,
  placa VARCHAR(10) NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'garagem',
  descricao TEXT NULL,
  preco_compra DECIMAL(12, 2) NULL,
  valor_fipe DECIMAL(12, 2) NULL,
  data_consulta_fipe DATE NULL,
  fipe_codigo VARCHAR(20) NULL,
  foto_url VARCHAR(500) NULL,
  visivel TINYINT(1) NOT NULL DEFAULT 1,
  ordem INTEGER NOT NULL DEFAULT 0,
  criado_em DATETIME NOT NULL,
  atualizado_em DATETIME NOT NULL,
  CONSTRAINT uq_veiculos_slug UNIQUE (usuario_id, slug),
  CONSTRAINT ck_veiculos_status CHECK (status IN ('garagem', 'projeto', 'vendido')),
  CONSTRAINT fk_veiculos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE
);
